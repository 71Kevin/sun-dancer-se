"""Turns out/qa/clip_report.json (tools/clip_test.py) into docs/QA.md.
  python tools/qa_report.py <clip_report.json> <QA.md> [<extra_checks.json>]
extra_checks.json: {"section title": ["markdown line", ...], ...} appended after the clipping tables (physics
validation, fringe visibility, bracelet rigidity...)."""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lib"))
from mk_testpresets import label  # noqa: E402  (preset names -> labels of tools/presets.local.json)

rep = json.load(open(sys.argv[1], encoding="utf-8"))
extra = json.load(open(sys.argv[3], encoding="utf-8")) if len(sys.argv) > 3 else {}
lines = ["# Clipping report", "",
         "Generated by `tools/clip_test.py` from the built BodySlide data (ShapeData NIF + OSD). A *poke* is a skin (or "
         "under-garment) vertex covered by a garment in the reference shape that ends up outside it by more than "
         "0.05 units (about 0.7 mm); depth in game units (1 unit ~ 1.4 cm).", "",
         "## Presets (weight 0 and 100)", ""]
static = rep["static"]
presets = list(next(iter(static.values()))["presets"].keys())
lines.append("| Test | covered verts | " + " | ".join(label(p) for p in presets) + " |")
lines.append("|---|---|" + "---|" * len(presets))
for name, r in static.items():
    cells = []
    for p in presets:
        x = r["presets"][p]
        cells.append("0" if x["pokes"] == 0 else "%d (%.2f)" % (x["pokes"], x["max_depth"]))
    lines.append("| %s | %d | %s |" % (name, r["covered_skin_verts"], " | ".join(cells)))
lines += ["", "## Animation poses (weight 100)", "",
          "Linear blend skinning with the game's skeleton; the cloth on the SMP physics chains (the hanging part of "
          "the Loincloth panels and of the Arm Veils) is left out, since in game the physics moves it. The arms' "
          "twist bones are posed with their parent bones (the animation reader decodes their tracks unreliably), "
          "for the skin and the garments alike.", ""]
poses = rep["poses"]
if poses:
    tests = list(next(iter(poses.values())).keys())
    # the keys are "<pose> | <preset>": two columns (the header used to lack the preset's, shifting every title)
    lines.append("| Pose | Preset | " + " | ".join(tests) + " |")
    lines.append("|---|---|" + "---|" * len(tests))
    for key, row in poses.items():
        cells = ["0" if row[t]["pokes"] == 0 else "%d (%.2f)" % (row[t]["pokes"], row[t]["max_depth"]) for t in tests]
        lines.append("| %s | %s |" % (label(key), " | ".join(cells)))
for title, body in extra.items():
    lines += ["", "## " + title, ""] + list(body)
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("written", sys.argv[2])
